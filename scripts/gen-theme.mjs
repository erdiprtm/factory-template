#!/usr/bin/env node
// Generates files derived from product.config.ts:
// - design-token CSS (light + dark, or light only with brand.darkMode false, D-076): apps/app/global.css (Tailwind v3 directives + tokens) and
//   apps/site/src/styles/tokens.css (tokens only);
// - apps/app/src/core/product.generated.json: the validated config (Zod defaults applied). Metro
//   serves it in place of product.config.ts, so the app bundle doesn't ship Zod (D-031);
// - apps/app/src/core/fonts.generated.ts: the bundled fonts for expo-font (static requires), and
//   @font-face rules in the site's tokens.css for the same files, self-hosted (D-052);
// - the installable web app (D-080): apps/app/public/index.html (Expo's single-page template with the
//   manifest, theme-color and Apple web-app tags), manifest.webmanifest, and the icons (192, 512,
//   maskable 512, apple-touch 180) from the product's one source icon (pwa.icon), with no image library
//   (scripts/png.mjs). With pwa.enabled false the manifest and icons are removed.
// Colors become HSL channels ("221 83% 53%") so Tailwind can use hsl(var(--x) / <alpha>).
//
// Usage: node scripts/gen-theme.mjs           # write
//        node scripts/gen-theme.mjs --check   # fail if the file is out of date (pnpm verify)

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { decodePng, encodePng, hexRgb, placeOnFill, resize } from "./png.mjs";

const OUTPUTS = {
  app: fileURLToPath(new URL("../apps/app/global.css", import.meta.url)),
  site: fileURLToPath(new URL("../apps/site/src/styles/tokens.css", import.meta.url)),
  appConfig: fileURLToPath(new URL("../apps/app/src/core/product.generated.json", import.meta.url)),
  appFonts: fileURLToPath(new URL("../apps/app/src/core/fonts.generated.ts", import.meta.url)),
  appHtml: fileURLToPath(new URL("../apps/app/public/index.html", import.meta.url)),
};
const APP_DIR = fileURLToPath(new URL("../apps/app/", import.meta.url));
const APP_PUBLIC = fileURLToPath(new URL("../apps/app/public/", import.meta.url));
const SITE_PUBLIC = fileURLToPath(new URL("../apps/site/public/", import.meta.url));

export function hexToHslChannels(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  const round = (x) => Math.round(x * 10) / 10;
  return `${round(h)} ${round(s * 100)}% ${round(l * 100)}%`;
}

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const HEADER = "/* GENERATED by scripts/gen-theme.mjs from product.config.ts. Do not edit; change the config. */";

/**
 * Element sizes as CSS variables (D-052). Defaults reproduce the template's look exactly: every
 * radius is --radius except the pill chip, and controls are 3rem (48 px on web), like h-12 today.
 * Values are literal (no nested var()), because NativeWind resolves one level on native.
 */
export function sizeVars(tokens) {
  const radii = tokens.radii ?? {};
  const r = (key, fallback) => radii[key] ?? fallback;
  return {
    "radius-card": r("card", tokens.radius),
    "radius-button": r("button", tokens.radius),
    "radius-input": r("input", tokens.radius),
    "radius-chip": r("chip", "9999px"),
    "radius-sheet": r("sheet", tokens.radius),
    "control-height": tokens.controlHeight ? `${tokens.controlHeight / 16}rem` : "3rem",
  };
}

/**
 * The token block: light in :root, dark in .dark:root (class on <html>). darkMode false (D-076):
 * light only, no .dark block.
 */
export function renderTokens(tokens, darkMode = true) {
  const block = (colors) =>
    Object.entries(colors)
      .map(([k, v]) => `    --${kebab(k)}: ${hexToHslChannels(v)};`)
      .join("\n");
  return [
    "@layer base {",
    "  :root {",
    block(tokens.colors.light),
    `    --radius: ${tokens.radius};`,
    ...Object.entries(sizeVars(tokens)).map(([k, v]) => `    --${k}: ${v};`),
    "  }",
    ...(darkMode ? ["  .dark:root {", block(tokens.colors.dark), "  }"] : []),
    "}",
    "",
  ].join("\n");
}

/** apps/app/global.css: Tailwind v3 directives (NativeWind) + tokens. */
export function renderTheme(tokens, darkMode = true) {
  return [
    HEADER,
    "@tailwind base;",
    "@tailwind components;",
    "@tailwind utilities;",
    "",
    renderTokens(tokens, darkMode),
  ].join("\n");
}

const formatOf = (file) =>
  ({ ttf: "truetype", otf: "opentype", woff: "woff", woff2: "woff2" })[file.split(".").pop()] ?? "truetype";

/** The site self-hosts the bundled fonts (apps/site/public/fonts): no request to Google (D-052). */
export function renderFontFaces(tokens) {
  const fonts = tokens.fonts ?? [];
  if (fonts.length === 0) return "";
  const faces = fonts.map(
    (f) =>
      `@font-face {\n  font-family: "${f.family}";\n  src: url("/fonts/${f.file}") format("${formatOf(f.file)}");\n  font-weight: ${f.weight ?? 400};\n  font-style: normal;\n  font-display: swap;\n}`,
  );
  const heading = tokens.fontFamily.heading ?? tokens.fontFamily.sans;
  return [
    ...faces,
    `:root {\n  --font-sans: "${tokens.fontFamily.sans}", system-ui, sans-serif;\n  --font-heading: "${heading}", system-ui, sans-serif;\n}`,
    "",
  ].join("\n");
}

/**
 * The name the app registers a bundled font file under: one per family AND weight (D-057), because
 * native platforms pick a font by file, not by font-weight. tailwind.config.js and @factory/ui use
 * the same `${family}_${weight}` names.
 */
export const fontKey = (family, weight = 400) => `${family}_${weight}`;

/** The app's bundled fonts for expo-font's useFonts (Metro needs static requires). */
export function renderAppFonts(tokens) {
  const lines = (tokens.fonts ?? []).map(
    (f) =>
      `  ${JSON.stringify(fontKey(f.family, f.weight))}: require(${JSON.stringify(`../../assets/fonts/${f.file}`)}),`,
  );
  return [
    "// GENERATED by scripts/gen-theme.mjs from product.config.ts brand.tokens.fonts. Do not edit.",
    "// Files live in apps/app/assets/fonts (product-owned), one entry per family and weight, named",
    '// "<family>_<weight>". Empty = the system font, as before (D-052, D-057).',
    "export const bundledFonts: Record<string, number> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

// ---- Installable web app (D-080) ----

/** Where each generated file is served (apps/app/public → the app Worker's assets). */
export const PWA_FILES = {
  manifest: "/manifest.webmanifest",
  icon192: "/icons/icon-192.png",
  icon512: "/icons/icon-512.png",
  maskable: "/icons/maskable-512.png",
  appleTouch: "/apple-touch-icon.png",
};
// ---- PNG and ICO favicons (D-096) ----

/** Served by the app and by the site alike (one domain may route a path to either). */
export const FAVICON_FILES = { png16: "/favicon-16.png", png32: "/favicon-32.png", ico: "/favicon.ico" };

/** The <link> tags, before the SVG favicon: browsers without SVG favicons, and crawlers, use these. */
export const faviconTags = () => [
  `<link rel="icon" href="${FAVICON_FILES.ico}" sizes="16x16 32x32" />`,
  `<link rel="icon" type="image/png" sizes="32x32" href="${FAVICON_FILES.png32}" />`,
  `<link rel="icon" type="image/png" sizes="16x16" href="${FAVICON_FILES.png16}" />`,
];

/** 16 and 32 px favicons, keyed by served path: the hand-made ones (exact sizes) or the source scaled down. */
export function renderFavicons(source, own = null) {
  if (own) {
    for (const size of [16, 32]) {
      const img = own[size];
      if (img.width !== size || img.height !== size)
        throw new Error(`brand.faviconPng.${size} must be ${size}x${size} (it is ${img.width}x${img.height})`);
    }
    return { [FAVICON_FILES.png16]: own[16], [FAVICON_FILES.png32]: own[32] };
  }
  return { [FAVICON_FILES.png16]: resize(source, 16), [FAVICON_FILES.png32]: resize(source, 32) };
}

/** A .ico holding PNG images (read by every current browser), smallest first. */
export function encodeIco(pngs) {
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, bytes }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4); // colour planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(bytes.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += bytes.length;
  });
  return Buffer.concat([header, ...pngs.map((p) => p.bytes)]);
}

/** The images inside a .ico written by encodeIco. */
export function decodeIco(buf) {
  if (buf.readUInt16LE(0) !== 0 || buf.readUInt16LE(2) !== 1) throw new Error("not an .ico file");
  return Array.from({ length: buf.readUInt16LE(4) }, (_, i) => {
    const e = 6 + 16 * i;
    const start = buf.readUInt32LE(e + 12);
    return decodePng(buf.subarray(start, start + buf.readUInt32LE(e + 8)));
  });
}

/** start_url: "?source=pwa" tells an open from the home screen apart (pwa_open). */
export const PWA_START_URL = "/?source=pwa";

const escapeHtml = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

/** The web app manifest: what Chrome needs to install (name, 192 + 512 icons, start_url, display). */
export function renderManifest(product) {
  const light = product.brand.tokens.colors.light;
  return {
    id: "/",
    name: product.name,
    short_name: product.pwa.shortName ?? product.name,
    description: product.tagline,
    lang: product.locale.default,
    dir: "ltr",
    start_url: PWA_START_URL,
    scope: "/",
    display: "standalone",
    theme_color: light.primary,
    background_color: light.background,
    icons: [
      { src: PWA_FILES.icon192, sizes: "192x192", type: "image/png", purpose: "any" },
      { src: PWA_FILES.icon512, sizes: "512x512", type: "image/png", purpose: "any" },
      { src: PWA_FILES.maskable, sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
  };
}

/**
 * apps/app/public/index.html: Expo's own single-page template (@expo/cli static/template), which
 * `expo export` and `expo start` use when this file exists, plus the installable-app tags. Static,
 * not expo-router/head (which adds tags only once the bundle runs): browsers read the manifest and
 * the Apple tags from the HTML they load.
 */
export function renderIndexHtml(product) {
  const pwaTags = product.pwa.enabled
    ? [
        `    <meta name="theme-color" content="${product.brand.tokens.colors.light.primary}" />`,
        `    <link rel="manifest" href="${PWA_FILES.manifest}" />`,
        `    <link rel="icon" type="image/png" sizes="192x192" href="${PWA_FILES.icon192}" />`,
        `    <link rel="apple-touch-icon" href="${PWA_FILES.appleTouch}" />`,
        '    <meta name="mobile-web-app-capable" content="yes" />',
        '    <meta name="apple-mobile-web-app-capable" content="yes" />',
        `    <meta name="apple-mobile-web-app-title" content="${escapeHtml(product.pwa.shortName ?? product.name)}" />`,
        '    <meta name="apple-mobile-web-app-status-bar-style" content="default" />',
      ]
    : [];
  return [
    "<!DOCTYPE html>",
    "<!-- GENERATED by scripts/gen-theme.mjs from product.config.ts (D-080). Do not edit; change the config. -->",
    `<html lang="${product.locale.default}">`,
    "  <head>",
    '    <meta charset="utf-8" />',
    '    <meta httpEquiv="X-UA-Compatible" content="IE=edge" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no" />',
    `    <title>${escapeHtml(product.name)}</title>`,
    ...faviconTags().map((tag) => `    ${tag}`),
    ...pwaTags,
    "    <!-- The `react-native-web` recommended style reset: https://necolas.github.io/react-native-web/docs/setup/#root-element -->",
    '    <style id="expo-reset">',
    "      /* These styles make the body full-height */",
    "      html,",
    "      body {",
    "        height: 100%;",
    "      }",
    "      /* These styles disable body scrolling if you are using <ScrollView> */",
    "      body {",
    "        overflow: hidden;",
    "      }",
    "      /* These styles make the root element full-height */",
    "      #root {",
    "        display: flex;",
    "        height: 100%;",
    "        flex: 1;",
    "      }",
    "    </style>",
    "  </head>",
    "",
    "  <body>",
    "    <noscript>",
    "      You need to enable JavaScript to run this app.",
    "    </noscript>",
    '    <div id="root"></div>',
    "  </body>",
    "</html>",
    "",
  ].join("\n");
}

/** Reads a source icon and checks it: a square PNG of at least 512 px. */
export function readSourceIcon(file) {
  let img;
  try {
    img = decodePng(readFileSync(file));
  } catch (e) {
    throw new Error(`pwa icon ${file}: ${e.code === "ENOENT" ? "file not found" : e.message}`);
  }
  if (img.width !== img.height) throw new Error(`pwa icon ${file} must be square (it is ${img.width}x${img.height})`);
  if (img.width < 512) throw new Error(`pwa icon ${file} must be at least 512 px (it is ${img.width})`);
  return img;
}

/** The colour behind a padded icon: the source's own corner if it's opaque (full-bleed), else background. */
export function fillFor(img, background) {
  return img.data[3] === 255 ? [img.data[0], img.data[1], img.data[2]] : hexRgb(background);
}

/**
 * Every icon size, as RGBA images keyed by served path:
 * - 192 and 512 ("any"): the source scaled, transparency kept;
 * - maskable 512: pwa.maskableIcon scaled as is, or the icon at 80% (inside Android's safe zone)
 *   on its fill colour;
 * - apple-touch-icon 180: the icon on its fill colour, opaque (iOS shows transparent pixels black).
 */
export function renderIcons(icon, background, maskableSource = null) {
  const fill = fillFor(icon, background);
  return {
    [PWA_FILES.icon192]: resize(icon, 192),
    [PWA_FILES.icon512]: resize(icon, 512),
    [PWA_FILES.maskable]: maskableSource
      ? placeOnFill(maskableSource, 512, 1, fillFor(maskableSource, background))
      : placeOnFill(icon, 512, 0.8, fill),
    [PWA_FILES.appleTouch]: placeOnFill(icon, 180, 1, fill),
  };
}

const publicPath = (served) => `${APP_PUBLIC}${served.slice(1)}`;
const sitePath = (served) => `${SITE_PUBLIC}${served.slice(1)}`;

/** Whether a .ico on disk holds exactly these images (pixels, not bytes). */
function sameIco(file, imgs) {
  try {
    const cur = decodeIco(readFileSync(file));
    return (
      cur.length === imgs.length &&
      cur.every(
        (c, i) =>
          c.width === imgs[i].width &&
          c.height === imgs[i].height &&
          Buffer.from(c.data).equals(Buffer.from(imgs[i].data)),
      )
    );
  } catch {
    return false;
  }
}

/** Whether a PNG on disk has exactly these pixels (the bytes can differ between zlib builds). */
function samePixels(file, img) {
  try {
    const cur = decodePng(readFileSync(file));
    return cur.width === img.width && cur.height === img.height && Buffer.from(cur.data).equals(Buffer.from(img.data));
  } catch {
    return false;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { default: product } = await import("../product.config.ts");
  const files = {
    [OUTPUTS.app]: renderTheme(product.brand.tokens, product.brand.darkMode),
    [OUTPUTS.site]: `${HEADER}\n${renderFontFaces(product.brand.tokens)}${renderTokens(product.brand.tokens, product.brand.darkMode)}`,
    [OUTPUTS.appConfig]: `${JSON.stringify(product, null, 2)}\n`,
    [OUTPUTS.appFonts]: renderAppFonts(product.brand.tokens),
    [OUTPUTS.appHtml]: renderIndexHtml(product),
  };
  const icons = {};
  if (product.pwa.enabled) {
    files[publicPath(PWA_FILES.manifest)] = `${JSON.stringify(renderManifest(product), null, 2)}\n`;
    const source = readSourceIcon(`${APP_DIR}${product.pwa.icon}`);
    const maskable = product.pwa.maskableIcon ? readSourceIcon(`${APP_DIR}${product.pwa.maskableIcon}`) : null;
    const background = product.brand.tokens.colors.light.background;
    for (const [served, img] of Object.entries(renderIcons(source, background, maskable)))
      icons[publicPath(served)] = img;
  }
  // Favicons (D-096), installable or not: the hand-made ones, or pwa.icon scaled down.
  const own = product.brand.faviconPng;
  const favicons = own
    ? renderFavicons(null, {
        16: decodePng(readFileSync(`${APP_DIR}${own[16]}`)),
        32: decodePng(readFileSync(`${APP_DIR}${own[32]}`)),
      })
    : renderFavicons(readSourceIcon(`${APP_DIR}${product.pwa.icon}`));
  for (const [served, img] of Object.entries(favicons)) {
    icons[publicPath(served)] = img;
    icons[sitePath(served)] = img;
  }
  const icoImages = [favicons[FAVICON_FILES.png16], favicons[FAVICON_FILES.png32]];
  const check = process.argv.includes("--check");
  let stale = false;
  for (const file of [publicPath(FAVICON_FILES.ico), sitePath(FAVICON_FILES.ico)]) {
    if (sameIco(file, icoImages)) continue;
    if (check) {
      console.error(`${file} is out of date (the favicon source changed). Run: pnpm theme`);
      stale = true;
    } else {
      writeFileSync(file, encodeIco(icoImages.map((img) => ({ size: img.width, bytes: encodePng(img) }))));
      console.log(`Wrote ${file}`);
    }
  }
  for (const [file, img] of Object.entries(icons)) {
    if (samePixels(file, img)) continue;
    if (check) {
      console.error(`${file} is out of date (pwa.icon changed). Run: pnpm theme`);
      stale = true;
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, encodePng(img));
      console.log(`Wrote ${file}`);
    }
  }
  // pwa.enabled false: no manifest and no icons left behind.
  for (const file of product.pwa.enabled ? [] : Object.values(PWA_FILES).map(publicPath)) {
    if (!existsSync(file)) continue;
    if (check) {
      console.error(`${file} should not exist (pwa.enabled is false). Run: pnpm theme`);
      stale = true;
    } else {
      rmSync(file);
      console.log(`Removed ${file}`);
    }
  }
  for (const [file, css] of Object.entries(files)) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {}
    if (current === css) continue;
    if (check) {
      console.error(`${file} is out of date (product.config.ts changed). Run: pnpm theme`);
      stale = true;
    } else {
      writeFileSync(file, css);
      console.log(`Wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log("Theme files are up to date.");
}
