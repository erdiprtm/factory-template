#!/usr/bin/env node
// Generates the design-token CSS (light + dark) from product.config.ts brand tokens.
// Output: apps/app/global.css (Tailwind directives + tokens); the Astro site reuses renderTheme().
// Colors become HSL channels ("221 83% 53%") so Tailwind can use hsl(var(--x) / <alpha>).
//
// Usage: node scripts/gen-theme.mjs           # write
//        node scripts/gen-theme.mjs --check   # fail if the file is out of date (pnpm verify)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../apps/app/global.css", import.meta.url));

export function hexToHslChannels(hex) {
  const n = Number.parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  const round = (x) => Math.round(x * 10) / 10;
  return `${round(h)} ${round(s * 100)}% ${round(l * 100)}%`;
}

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

export function renderTheme(tokens) {
  const block = (colors) =>
    Object.entries(colors)
      .map(([k, v]) => `    --${kebab(k)}: ${hexToHslChannels(v)};`)
      .join("\n");
  return [
    "/* GENERATED by scripts/gen-theme.mjs from product.config.ts. Do not edit; change the config. */",
    "@tailwind base;",
    "@tailwind components;",
    "@tailwind utilities;",
    "",
    "@layer base {",
    "  :root {",
    block(tokens.colors.light),
    `    --radius: ${tokens.radius};`,
    "  }",
    "  .dark:root {",
    block(tokens.colors.dark),
    "  }",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { default: product } = await import("../product.config.ts");
  const css = renderTheme(product.brand.tokens);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {}
    if (current !== css) {
      console.error("apps/app/global.css is out of date. Run: node scripts/gen-theme.mjs");
      process.exit(1);
    }
    console.log("global.css is up to date.");
  } else {
    writeFileSync(OUT, css);
    console.log(`Wrote ${OUT}`);
  }
}
