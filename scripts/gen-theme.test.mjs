import { describe, expect, it } from "vitest";
import {
  fontKey,
  hexToHslChannels,
  renderAppFonts,
  renderFontFaces,
  renderTheme,
  renderTokens,
  sizeVars,
} from "./gen-theme.mjs";

describe("gen-theme", () => {
  it("converts hex to HSL channels", () => {
    expect(hexToHslChannels("#ffffff")).toBe("0 0% 100%");
    expect(hexToHslChannels("#000000")).toBe("0 0% 0%");
    expect(hexToHslChannels("#2563eb")).toBe("221.2 83.2% 53.3%");
    expect(hexToHslChannels("#dc2626")).toBe("0 72.2% 50.6%");
  });

  it("renders light and dark blocks with kebab-case token names", () => {
    const css = renderTheme({
      colors: { light: { primaryForeground: "#ffffff" }, dark: { primaryForeground: "#000000" } },
      radius: "0.75rem",
    });
    expect(css).toContain(":root {\n    --primary-foreground: 0 0% 100%;\n    --radius: 0.75rem;");
    expect(css).toContain(".dark:root {\n    --primary-foreground: 0 0% 0%;");
  });

  it("light-only products (darkMode false) get no .dark block (D-076)", () => {
    const tokens = { colors: { light: { primaryForeground: "#ffffff" } }, radius: "0.75rem" };
    const css = renderTheme(tokens, false);
    expect(css).not.toContain(".dark");
    expect(css).toContain(":root {\n    --primary-foreground: 0 0% 100%;");
    expect(renderTokens(tokens, false)).toMatchInlineSnapshot(`
      "@layer base {
        :root {
          --primary-foreground: 0 0% 100%;
          --radius: 0.75rem;
          --radius-card: 0.75rem;
          --radius-button: 0.75rem;
          --radius-input: 0.75rem;
          --radius-chip: 9999px;
          --radius-sheet: 0.75rem;
          --control-height: 3rem;
        }
      }
      "
    `);
    // Default (true): the dark block stays, as before.
    expect(renderTokens({ ...tokens, colors: { ...tokens.colors, dark: { primaryForeground: "#000000" } } })).toContain(
      ".dark:root {",
    );
  });

  it("writes per-element sizes; the defaults reproduce today's look (D-052)", () => {
    expect(sizeVars({ radius: "0.75rem" })).toEqual({
      "radius-card": "0.75rem",
      "radius-button": "0.75rem",
      "radius-input": "0.75rem",
      "radius-chip": "9999px",
      "radius-sheet": "0.75rem",
      "control-height": "3rem",
    });
    const css = renderTheme({
      colors: { light: {}, dark: {} },
      radius: "0.75rem",
      radii: { button: "9999px", card: "20px" },
      controlHeight: 56,
    });
    expect(css).toContain("--radius-button: 9999px;");
    expect(css).toContain("--radius-card: 20px;");
    expect(css).toContain("--radius-input: 0.75rem;");
    expect(css).toContain("--control-height: 3.5rem;");
  });

  it("self-hosts bundled fonts on the site and maps them for expo-font", () => {
    const tokens = {
      fontFamily: { sans: "Plus Jakarta Sans", heading: "Fredoka" },
      fonts: [
        { family: "Fredoka", file: "Fredoka-SemiBold.ttf", weight: 600 },
        { family: "Plus Jakarta Sans", file: "PlusJakartaSans.otf", weight: 400 },
      ],
    };
    const faces = renderFontFaces(tokens);
    expect(faces).toContain('src: url("/fonts/Fredoka-SemiBold.ttf") format("truetype");');
    expect(faces).toContain('format("opentype")');
    expect(faces).toContain('--font-heading: "Fredoka", system-ui, sans-serif;');
    expect(faces).not.toContain("googleapis");
    expect(renderAppFonts(tokens)).toContain('"Fredoka_600": require("../../assets/fonts/Fredoka-SemiBold.ttf"),');
    expect(renderFontFaces({ fontFamily: { sans: "Inter" }, fonts: [] })).toBe("");
    expect(renderAppFonts({ fonts: [] })).toContain("bundledFonts: Record<string, number> = {\n};");
  });

  it("bundles several weights of one family under distinct names (D-057)", () => {
    const weights = [400, 500, 600, 700, 800];
    const tokens = {
      fontFamily: { sans: "Plus Jakarta Sans" },
      fonts: weights.map((weight) => ({ family: "Plus Jakarta Sans", file: `PlusJakartaSans-${weight}.ttf`, weight })),
    };
    const app = renderAppFonts(tokens);
    const keys = [...app.matchAll(/^ {2}"([^"]+)":/gm)].map((m) => m[1]);
    expect(keys).toEqual(weights.map((w) => fontKey("Plus Jakarta Sans", w)));
    expect(new Set(keys).size).toBe(keys.length); // no duplicate object keys (TS1117)
    expect(app).toMatchInlineSnapshot(`
      "// GENERATED by scripts/gen-theme.mjs from product.config.ts brand.tokens.fonts. Do not edit.
      // Files live in apps/app/assets/fonts (product-owned), one entry per family and weight, named
      // "<family>_<weight>". Empty = the system font, as before (D-052, D-057).
      export const bundledFonts: Record<string, number> = {
        "Plus Jakarta Sans_400": require("../../assets/fonts/PlusJakartaSans-400.ttf"),
        "Plus Jakarta Sans_500": require("../../assets/fonts/PlusJakartaSans-500.ttf"),
        "Plus Jakarta Sans_600": require("../../assets/fonts/PlusJakartaSans-600.ttf"),
        "Plus Jakarta Sans_700": require("../../assets/fonts/PlusJakartaSans-700.ttf"),
        "Plus Jakarta Sans_800": require("../../assets/fonts/PlusJakartaSans-800.ttf"),
      };
      "
    `);
    // The site keeps one family with a face per weight.
    expect(renderFontFaces(tokens).match(/font-family: "Plus Jakarta Sans";/g)).toHaveLength(5);
    expect(renderFontFaces(tokens)).toContain("font-weight: 800;");
  });
});
