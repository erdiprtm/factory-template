import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { defineProduct } from "../packages/config/src/index.ts";
import product from "../product.config.ts";
import {
  decodeIco,
  encodeIco,
  FAVICON_FILES,
  faviconTags,
  fillFor,
  fontKey,
  hexToHslChannels,
  PWA_FILES,
  PWA_START_URL,
  renderAppFonts,
  renderFavicons,
  renderFontFaces,
  renderIcons,
  renderIndexHtml,
  renderManifest,
  renderTheme,
  renderTokens,
  sizeVars,
} from "./gen-theme.mjs";
import { encodePng, pngSize } from "./png.mjs";

describe("gen-theme", () => {
  it("converts hex to HSL channels", () => {
    expect(hexToHslChannels("#ffffff")).toBe("0 0% 100%");
    expect(hexToHslChannels("#000000")).toBe("0 0% 0%");
    expect(hexToHslChannels("#2563eb")).toBe("221.2 83.2% 53.3%");
    expect(hexToHslChannels("#dc2626")).toBe("0 72.2% 50.6%");
  });

  it("renders light and dark blocks with kebab-case token names", () => {
    const css = renderTheme({
      colors: { light: { primaryForeground: "#ffffff" }, dark: { primaryForeground: "#000000" } },
      radius: "0.75rem",
    });
    expect(css).toContain(":root {\n    --primary-foreground: 0 0% 100%;\n    --radius: 0.75rem;");
    expect(css).toContain(".dark:root {\n    --primary-foreground: 0 0% 0%;");
  });

  it("light-only products (darkMode false) get no .dark block (D-076)", () => {
    const tokens = { colors: { light: { primaryForeground: "#ffffff" } }, radius: "0.75rem" };
    const css = renderTheme(tokens, false);
    expect(css).not.toContain(".dark");
    expect(css).toContain(":root {\n    --primary-foreground: 0 0% 100%;");
    expect(renderTokens(tokens, false)).toMatchInlineSnapshot(`
      "@layer base {
        :root {
          --primary-foreground: 0 0% 100%;
          --radius: 0.75rem;
          --radius-card: 0.75rem;
          --radius-button: 0.75rem;
          --radius-input: 0.75rem;
          --radius-chip: 9999px;
          --radius-sheet: 0.75rem;
          --control-height: 3rem;
        }
      }
      "
    `);
    // Default (true): the dark block stays, as before.
    expect(renderTokens({ ...tokens, colors: { ...tokens.colors, dark: { primaryForeground: "#000000" } } })).toContain(
      ".dark:root {",
    );
  });

  it("writes per-element sizes; the defaults reproduce today's look (D-052)", () => {
    expect(sizeVars({ radius: "0.75rem" })).toEqual({
      "radius-card": "0.75rem",
      "radius-button": "0.75rem",
      "radius-input": "0.75rem",
      "radius-chip": "9999px",
      "radius-sheet": "0.75rem",
      "control-height": "3rem",
    });
    const css = renderTheme({
      colors: { light: {}, dark: {} },
      radius: "0.75rem",
      radii: { button: "9999px", card: "20px" },
      controlHeight: 56,
    });
    expect(css).toContain("--radius-button: 9999px;");
    expect(css).toContain("--radius-card: 20px;");
    expect(css).toContain("--radius-input: 0.75rem;");
    expect(css).toContain("--control-height: 3.5rem;");
  });

  it("self-hosts bundled fonts on the site and maps them for expo-font", () => {
    const tokens = {
      fontFamily: { sans: "Plus Jakarta Sans", heading: "Fredoka" },
      fonts: [
        { family: "Fredoka", file: "Fredoka-SemiBold.ttf", weight: 600 },
        { family: "Plus Jakarta Sans", file: "PlusJakartaSans.otf", weight: 400 },
      ],
    };
    const faces = renderFontFaces(tokens);
    expect(faces).toContain('src: url("/fonts/Fredoka-SemiBold.ttf") format("truetype");');
    expect(faces).toContain('format("opentype")');
    expect(faces).toContain('--font-heading: "Fredoka", system-ui, sans-serif;');
    expect(faces).not.toContain("googleapis");
    expect(renderAppFonts(tokens)).toContain('"Fredoka_600": require("../../assets/fonts/Fredoka-SemiBold.ttf"),');
    expect(renderFontFaces({ fontFamily: { sans: "Inter" }, fonts: [] })).toBe("");
    expect(renderAppFonts({ fonts: [] })).toContain("bundledFonts: Record<string, number> = {\n};");
  });

  it("bundles several weights of one family under distinct names (D-057)", () => {
    const weights = [400, 500, 600, 700, 800];
    const tokens = {
      fontFamily: { sans: "Plus Jakarta Sans" },
      fonts: weights.map((weight) => ({ family: "Plus Jakarta Sans", file: `PlusJakartaSans-${weight}.ttf`, weight })),
    };
    const app = renderAppFonts(tokens);
    const keys = [...app.matchAll(/^ {2}"([^"]+)":/gm)].map((m) => m[1]);
    expect(keys).toEqual(weights.map((w) => fontKey("Plus Jakarta Sans", w)));
    expect(new Set(keys).size).toBe(keys.length); // no duplicate object keys (TS1117)
    expect(app).toMatchInlineSnapshot(`
      "// GENERATED by scripts/gen-theme.mjs from product.config.ts brand.tokens.fonts. Do not edit.
      // Files live in apps/app/assets/fonts (product-owned), one entry per family and weight, named
      // "<family>_<weight>". Empty = the system font, as before (D-052, D-057).
      export const bundledFonts: Record<string, number> = {
        "Plus Jakarta Sans_400": require("../../assets/fonts/PlusJakartaSans-400.ttf"),
        "Plus Jakarta Sans_500": require("../../assets/fonts/PlusJakartaSans-500.ttf"),
        "Plus Jakarta Sans_600": require("../../assets/fonts/PlusJakartaSans-600.ttf"),
        "Plus Jakarta Sans_700": require("../../assets/fonts/PlusJakartaSans-700.ttf"),
        "Plus Jakarta Sans_800": require("../../assets/fonts/PlusJakartaSans-800.ttf"),
      };
      "
    `);
    // The site keeps one family with a face per weight.
    expect(renderFontFaces(tokens).match(/font-family: "Plus Jakarta Sans";/g)).toHaveLength(5);
    expect(renderFontFaces(tokens)).toContain("font-weight: 800;");
  });
});

describe("installable web app (D-080)", () => {
  const base = { ...product, pwa: { ...product.pwa, enabled: true, shortName: null } };

  it("the manifest has everything Chrome needs to install, colours from the brand", () => {
    const m = renderManifest(base);
    expect(m.name).toBe(product.name);
    expect(m.short_name).toBe(product.name);
    expect(m.lang).toBe(product.locale.default);
    expect(m.start_url).toBe(PWA_START_URL);
    expect(m.start_url).toBe("/?source=pwa");
    expect(m.scope).toBe("/");
    expect(m.display).toBe("standalone");
    expect(m.theme_color).toBe(product.brand.tokens.colors.light.primary);
    expect(m.background_color).toBe(product.brand.tokens.colors.light.background);
    expect(m).not.toHaveProperty("prefer_related_applications");
    const sizes = m.icons.map((i) => `${i.sizes} ${i.purpose}`);
    expect(sizes).toEqual(["192x192 any", "512x512 any", "512x512 maskable"]);
    expect(renderManifest({ ...base, pwa: { ...base.pwa, shortName: "Fit" } }).short_name).toBe("Fit");
  });

  it("index.html carries the manifest, theme-color and Apple tags only when enabled", () => {
    const html = renderIndexHtml({ ...base, name: 'A & "B"' });
    expect(html).toContain(`<html lang="${product.locale.default}">`);
    expect(html).toContain("<title>A &amp; &quot;B&quot;</title>");
    expect(html).toContain('<link rel="manifest" href="/manifest.webmanifest" />');
    expect(html).toContain(`<meta name="theme-color" content="${product.brand.tokens.colors.light.primary}" />`);
    expect(html).toContain('<link rel="apple-touch-icon" href="/apple-touch-icon.png" />');
    expect(html).toContain('<meta name="apple-mobile-web-app-capable" content="yes" />');
    expect(html).toContain('<div id="root"></div>');
    const off = renderIndexHtml({ ...base, pwa: { ...base.pwa, enabled: false } });
    expect(off).not.toContain("manifest");
    expect(off).not.toContain("apple-");
  });

  it("makes every size from one source; transparent sources get the background behind padded icons", () => {
    const src = { width: 512, height: 512, data: new Uint8Array(512 * 512 * 4) }; // fully transparent
    const icons = renderIcons(src, "#ffffff");
    const dims = Object.fromEntries(Object.entries(icons).map(([k, v]) => [k, `${v.width}x${v.height}`]));
    expect(dims).toEqual({
      [PWA_FILES.icon192]: "192x192",
      [PWA_FILES.icon512]: "512x512",
      [PWA_FILES.maskable]: "512x512",
      [PWA_FILES.appleTouch]: "180x180",
    });
    expect(fillFor(src, "#ffffff")).toEqual([255, 255, 255]);
    // Maskable and apple-touch are opaque (full-bleed); the "any" icons keep transparency.
    expect([...icons[PWA_FILES.maskable].data.subarray(0, 4)]).toEqual([255, 255, 255, 255]);
    expect([...icons[PWA_FILES.appleTouch].data.subarray(0, 4)]).toEqual([255, 255, 255, 255]);
    expect(icons[PWA_FILES.icon192].data[3]).toBe(0);
  });

  it("favicons (D-096): pwa.icon scaled to 16 and 32, or hand-made ones at exactly those sizes", () => {
    const blank = (n) => ({ width: n, height: n, data: new Uint8Array(n * n * 4).fill(200) });
    const scaled = renderFavicons(blank(512));
    expect([scaled[FAVICON_FILES.png16].width, scaled[FAVICON_FILES.png32].width]).toEqual([16, 32]);
    const own = { 16: blank(16), 32: blank(32) };
    expect(renderFavicons(null, own)[FAVICON_FILES.png32]).toBe(own[32]);
    expect(() => renderFavicons(null, { 16: blank(16), 32: blank(48) })).toThrow(/faviconPng\.32 must be 32x32/);
  });

  it("a .ico holds the PNGs and reads back pixel for pixel", () => {
    const imgs = [16, 32].map((n) => ({ width: n, height: n, data: new Uint8Array(n * n * 4).fill(n) }));
    const ico = encodeIco(imgs.map((img) => ({ size: img.width, bytes: encodePng(img) })));
    expect([
      ico.readUInt16LE(0),
      ico.readUInt16LE(2),
      ico.readUInt16LE(4),
      ico.readUInt8(6),
      ico.readUInt8(22),
    ]).toEqual([0, 1, 2, 16, 32]);
    const back = decodeIco(ico);
    expect(back.map((b) => b.width)).toEqual([16, 32]);
    expect(Buffer.from(back[1].data).equals(Buffer.from(imgs[1].data))).toBe(true);
    expect(() => decodeIco(Buffer.alloc(8))).toThrow(/not an .ico/);
  });

  it("index.html links the PNG and ICO favicons, installable or not", () => {
    for (const enabled of [true, false]) {
      const html = renderIndexHtml({ ...base, pwa: { ...base.pwa, enabled } });
      for (const tag of faviconTags()) expect(html).toContain(tag);
    }
  });

  it("this product's favicons are written for the app and the site (pnpm theme)", () => {
    for (const dir of ["../apps/app/public/", "../apps/site/public/"]) {
      const pub = new URL(dir, import.meta.url);
      expect(pngSize(readFileSync(new URL("favicon-16.png", pub)))).toEqual({ width: 16, height: 16 });
      expect(pngSize(readFileSync(new URL("favicon-32.png", pub)))).toEqual({ width: 32, height: 32 });
      expect(decodeIco(readFileSync(new URL("favicon.ico", pub))).map((i) => i.width)).toEqual([16, 32]);
    }
  });

  it("config: on by default, offered nowhere until the product picks a moment", () => {
    const { pwa: _drop, ...input } = product;
    const parsed = defineProduct({ ...input, brand: { ...input.brand } });
    expect(parsed.pwa).toEqual({
      enabled: true,
      icon: "assets/icon.png",
      maskableIcon: null,
      shortName: null,
      promptAfter: "never",
    });
    expect(() => defineProduct({ ...input, pwa: { promptAfter: "soon" } })).toThrow();
    expect(() => defineProduct({ ...input, pwa: { icon: "/abs/icon.svg" } })).toThrow();
  });

  it.skipIf(!product.pwa.enabled)("this product's generated files are there, at the stated sizes (pnpm theme)", () => {
    const pub = new URL("../apps/app/public/", import.meta.url);
    const manifest = JSON.parse(readFileSync(new URL("manifest.webmanifest", pub), "utf8"));
    expect(manifest).toEqual(renderManifest(product));
    for (const icon of manifest.icons) {
      const file = new URL(icon.src.slice(1), pub);
      expect(existsSync(file), icon.src).toBe(true);
      const { width, height } = pngSize(readFileSync(file));
      expect(`${width}x${height}`).toBe(icon.sizes);
    }
    expect(manifest.icons.some((i) => i.purpose === "maskable")).toBe(true);
    expect(pngSize(readFileSync(new URL("apple-touch-icon.png", pub)))).toEqual({ width: 180, height: 180 });
    const source = pngSize(readFileSync(new URL(`../apps/app/${product.pwa.icon}`, import.meta.url)));
    expect(source.width).toBe(source.height);
    expect(source.width).toBeGreaterThanOrEqual(512);
    expect(readFileSync(new URL("index.html", pub), "utf8")).toBe(renderIndexHtml(product));
  });
});
